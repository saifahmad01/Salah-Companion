/**
 * Helper to retrieve Para/Juz for a given Quran page (1 to 604)
 */
export function getParaForQuranPage(pageNum: number): QuranParaMeta {
  if (pageNum <= 1) return QURAN_PARAS[0]
  for (let i = QURAN_PARAS.length - 1; i >= 0; i--) {
    if (pageNum >= QURAN_PARAS[i].startPage) {
      return QURAN_PARAS[i]
    }
  }
  return QURAN_PARAS[0]
}
